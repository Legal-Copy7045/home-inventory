"""Identity and permissions.

Two channels reach the backend:

``ingress``
    Requests proxied by the Home Assistant Supervisor's Ingress gateway.  The
    Supervisor authenticates the Home Assistant session before proxying and
    adds ``X-Remote-User-Id``, ``X-Remote-User-Name`` and
    ``X-Remote-User-Display-Name`` headers.  Because any process on the
    internal Docker network could forge those headers, the backend only
    trusts them when the TCP peer is the Supervisor's Ingress address
    (172.30.32.2).  The Ingress port is not published on the host.

``api``
    Requests from the companion Home Assistant integration on a separate
    internal port.  These must carry ``Authorization: Bearer <token>`` where
    the token is generated by the App, stored in ``/data`` and handed to Home
    Assistant through Supervisor discovery.  The integration may act on
    behalf of a Home Assistant user (service call context, or the sidebar
    proxy used on Container/Core installs) and then forwards that user's id,
    name and admin flag.

Roles: ``admin`` > ``member`` > ``read_only``.  A user's role is the explicit
override set by an administrator in the app, otherwise ``admin`` when the
user is a Home Assistant administrator or listed in ``admin_users``,
``read_only`` when listed in ``read_only_users``, else the configured default.
"""

from __future__ import annotations

import hmac
import logging
import secrets
import time
from dataclasses import dataclass
from datetime import UTC, datetime
from ipaddress import ip_address, ip_network
from typing import Any

from fastapi import Depends, HTTPException, Request
from sqlalchemy import select
from sqlalchemy.orm import Session

from .config import Settings
from .models import Role, User

_LOGGER = logging.getLogger(__name__)

ROLE_RANK = {Role.read_only: 0, Role.member: 1, Role.admin: 2}
SYSTEM_USER_ID = "system"
INTEGRATION_USER_ID = "integration"


@dataclass(frozen=True)
class Actor:
    user_id: int
    ha_user_id: str
    name: str
    role: Role
    channel: str

    def can(self, needed: Role) -> bool:
        return ROLE_RANK[self.role] >= ROLE_RANK[needed]


def load_or_create_token(settings: Settings) -> str:
    path = settings.token_path
    if path.exists():
        token = path.read_text().strip()
        if len(token) >= 32:
            return token
    token = secrets.token_urlsafe(32)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(token)
    try:
        path.chmod(0o600)
    except OSError:  # pragma: no cover
        pass
    return token


def peer_is_trusted(peer: str | None, trusted: list[str]) -> bool:
    if not peer:
        return False
    try:
        addr = ip_address(peer)
    except ValueError:
        return peer in trusted  # e.g. "testclient" in tests when configured
    for entry in trusted:
        try:
            if addr in ip_network(entry, strict=False):
                return True
        except ValueError:
            if entry == peer:
                return True
    return False


class HaAdminDirectory:
    """Looks up which Home Assistant users are administrators.

    Uses the Supervisor's proxy to Home Assistant's WebSocket API
    (``config/auth/list``), which is available to Apps that declare
    ``homeassistant_api: true``.  Results are cached; failures are logged and
    treated as "unknown" so the role falls back to app configuration.
    """

    TTL = 300

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self._cache: dict[str, bool] = {}
        self._fetched = 0.0
        self.available: bool | None = None

    def is_admin(self, ha_user_id: str) -> bool | None:
        if not self.settings.supervisor_token:
            return None
        if time.monotonic() - self._fetched > self.TTL:
            self._refresh()
        if not self.available:
            return None
        return self._cache.get(ha_user_id)

    def _refresh(self) -> None:
        self._fetched = time.monotonic()
        try:
            users = _ws_call(self.settings, {"type": "config/auth/list"})
        except Exception as err:  # noqa: BLE001
            if self.available is not False:
                _LOGGER.warning("Could not read Home Assistant users (%s); using configured roles", err)
            self.available = False
            return
        self._cache = {
            u["id"]: bool(u.get("is_owner")) or "system-admin" in (u.get("group_ids") or []) for u in users
        }
        self.available = True


def _ws_call(settings: Settings, message: dict[str, Any]) -> Any:
    """Minimal synchronous Home Assistant WebSocket call via the Supervisor."""
    import json

    from websockets.sync.client import connect  # type: ignore[import-not-found]

    url = settings.supervisor_url.replace("http", "ws", 1) + "/core/websocket"
    with connect(url, open_timeout=5, close_timeout=2) as ws:
        json.loads(ws.recv(timeout=5))  # auth_required
        ws.send(json.dumps({"type": "auth", "access_token": settings.supervisor_token}))
        auth = json.loads(ws.recv(timeout=5))
        if auth.get("type") != "auth_ok":
            raise RuntimeError("authentication with Home Assistant failed")
        ws.send(json.dumps({"id": 1, **message}))
        while True:
            reply = json.loads(ws.recv(timeout=10))
            if reply.get("id") == 1:
                if not reply.get("success"):
                    raise RuntimeError(reply.get("error", {}).get("message", "request failed"))
                return reply["result"]


def effective_role(user: User, settings: Settings) -> Role:
    if user.role_override is not None:
        return user.role_override
    ident = {user.ha_user_id, (user.username or "").lower(), (user.display_name or "").lower()}
    admins = {a.lower() for a in settings.admin_users} | set(settings.admin_users)
    readers = {a.lower() for a in settings.read_only_users} | set(settings.read_only_users)
    if user.ha_is_admin or ident & admins:
        return Role.admin
    if ident & readers:
        return Role.read_only
    return Role(settings.default_role)


def upsert_user(
    db: Session,
    ha_user_id: str,
    username: str | None,
    display_name: str | None,
    ha_is_admin: bool | None,
) -> User:
    user = db.scalar(select(User).where(User.ha_user_id == ha_user_id))
    now = datetime.now(UTC)
    if user is None:
        user = User(ha_user_id=ha_user_id, username=username, display_name=display_name, ha_is_admin=bool(ha_is_admin))
        db.add(user)
        db.flush()
        # Bootstrap: if Home Assistant cannot tell us who the administrators
        # are and none is configured, the first person to open the app
        # becomes the administrator so the app can be configured.
        if ha_is_admin is None and not _any_admin(db, user.id):
            user.role_override = Role.admin
            _LOGGER.warning("No administrator known; granting admin role to first user %s", display_name or ha_user_id)
    else:
        if username:
            user.username = username
        if display_name:
            user.display_name = display_name
        if ha_is_admin is not None:
            user.ha_is_admin = ha_is_admin
        # Throttle last_seen writes.
        last = user.last_seen if user.last_seen.tzinfo else user.last_seen.replace(tzinfo=UTC)
        if (now - last).total_seconds() > 60:
            user.last_seen = now
    db.commit()
    return user


def _any_admin(db: Session, exclude_id: int) -> bool:
    users = db.scalars(select(User).where(User.id != exclude_id)).all()
    return any(u.role_override == Role.admin or u.ha_is_admin for u in users)


def system_user(db: Session, ha_user_id: str = SYSTEM_USER_ID, name: str = "System") -> User:
    user = db.scalar(select(User).where(User.ha_user_id == ha_user_id))
    if user is None:
        user = User(ha_user_id=ha_user_id, username=ha_user_id, display_name=name, role_override=Role.member)
        db.add(user)
        db.commit()
    return user


def _header(request: Request, name: str) -> str | None:
    value = request.headers.get(name)
    if value is None:
        return None
    value = value.strip()
    return value[:128] or None


def resolve_actor(request: Request, db: Session) -> Actor:
    state = request.app.state
    settings: Settings = state.settings
    channel: str = state.channel

    if channel == "ingress":
        peer = request.client.host if request.client else None
        if not peer_is_trusted(peer, settings.trusted_proxies):
            _LOGGER.warning("Rejected Ingress request from untrusted peer %s", peer)
            raise HTTPException(status_code=403, detail="Requests must come through Home Assistant Ingress")
        ha_id = _header(request, "X-Remote-User-Id")
        if not ha_id:
            raise HTTPException(status_code=401, detail="Home Assistant user identity missing")
        is_admin = state.admin_directory.is_admin(ha_id)
        user = upsert_user(
            db,
            ha_id,
            _header(request, "X-Remote-User-Name"),
            _header(request, "X-Remote-User-Display-Name"),
            is_admin,
        )
    else:
        auth = request.headers.get("Authorization", "")
        scheme, _, token = auth.partition(" ")
        if scheme.lower() != "bearer" or not hmac.compare_digest(token.strip().encode(), state.api_token.encode()):
            raise HTTPException(status_code=401, detail="Invalid API token", headers={"WWW-Authenticate": "Bearer"})
        ha_id = _header(request, "X-Remote-User-Id")
        if ha_id:
            admin_hdr = _header(request, "X-Remote-User-Is-Admin")
            user = upsert_user(
                db,
                ha_id,
                _header(request, "X-Remote-User-Name"),
                _header(request, "X-Remote-User-Display-Name"),
                None if admin_hdr is None else admin_hdr.lower() in ("1", "true", "yes"),
            )
        else:
            user = system_user(db, INTEGRATION_USER_ID, "Home Assistant")

    role = effective_role(user, settings)
    return Actor(
        user_id=user.id,
        ha_user_id=user.ha_user_id,
        name=user.display_name or user.username or user.ha_user_id,
        role=role,
        channel=channel,
    )


def get_db(request: Request):
    yield from request.app.state.db.session()


def current_actor(request: Request, db: Session = Depends(get_db)) -> Actor:
    actor = resolve_actor(request, db)
    if request.method not in ("GET", "HEAD", "OPTIONS") and not actor.can(Role.member):
        raise HTTPException(status_code=403, detail="Your account has read-only access")
    return actor


def require_member(actor: Actor = Depends(current_actor)) -> Actor:
    if not actor.can(Role.member):
        raise HTTPException(status_code=403, detail="Your account has read-only access")
    return actor


def require_admin(actor: Actor = Depends(current_actor)) -> Actor:
    if not actor.can(Role.admin):
        raise HTTPException(status_code=403, detail="Administrator access required")
    return actor
